async function main() {
  setColorVariables();
  setNumberVariables();
  await setTextStyles();
  setEffectStyles();
  await buildContractPage();
  await buildTokenPage();
  await buildComponentPage();
  figma.root.setSharedPluginData('polaris.design', 'upstreamCommit', POLARIS_SYNC_DATA.tokens.source.commit);
  figma.root.setSharedPluginData('polaris.design', 'tokensJsonSha256', POLARIS_SYNC_DATA.manifest.tokensJsonSha256);
  figma.root.setSharedPluginData('polaris.design', 'syncedAt', POLARIS_SYNC_DATA.tokens.generatedAt);
  const colorCollection = figma.variables
    .getLocalVariableCollections()
    .find((collection) => collection.name === 'Polaris / Color');
  const numberCollection = figma.variables
    .getLocalVariableCollections()
    .find((collection) => collection.name === 'Polaris / Number');
  const localVariables = figma.variables.getLocalVariables();
  const pages = figma.root.children
    .filter((page) => page.name === '00 Polaris Output Contract' || page.name.startsWith('Polaris DS - '))
    .map((page) => ({ id: page.id, name: page.name }));
  return {
    status: 'synced',
    pages,
    colorVariables: colorCollection
      ? localVariables.filter((variable) => variable.variableCollectionId === colorCollection.id).length
      : 0,
    numberVariables: numberCollection
      ? localVariables.filter((variable) => variable.variableCollectionId === numberCollection.id).length
      : 0,
    textStyles: figma.getLocalTextStyles().filter((style) => style.name.startsWith('Polaris/')).length,
    effectStyles: figma.getLocalEffectStyles().filter((style) => style.name.startsWith('Polaris/shadow/')).length,
    sharedPluginData: {
      upstreamCommit: figma.root.getSharedPluginData('polaris.design', 'upstreamCommit'),
      tokensJsonSha256: figma.root.getSharedPluginData('polaris.design', 'tokensJsonSha256'),
      syncedAt: figma.root.getSharedPluginData('polaris.design', 'syncedAt'),
    },
  };
}

return await main();
